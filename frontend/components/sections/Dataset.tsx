export function DefectTaxonomy() {
  const [active, setActive] = useState<(typeof CLASS_NAMES)[number]>(CLASS_NAMES[0]);

  return (
    <section className="border-b border-border bg-background py-24">
      <div className="mx-auto max-w-6xl px-6">
        <Reveal>
          <SectionHeading
            eyebrow="Defect Taxonomy"
            title="Six Categories of PCB Defect"
            description="Every prediction in this project belongs to one of these six DeepPCB defect classes. Average Precision (AP) is the held-out test-split value for that class."
          />
        </Reveal>

        <div className="mt-14 grid gap-6 lg:grid-cols-[320px_1fr]">
          <div className="flex flex-col gap-2">
            {CLASS_NAMES.map((c, i) => (
              <button
                key={c}
                onClick={() => setActive(c)}
                className={`flex items-center justify-between rounded-lg border px-4 py-3 text-left transition-colors ${
                  active === c
                    ? "border-accent/40 bg-accent-soft text-foreground"
                    : "border-border bg-surface-2/40 text-muted hover:border-border-strong"
                }`}
              >
                <span className="flex items-center gap-3">
                  <span className="font-mono text-xs text-muted-2">{String(i + 1).padStart(2, "0")}</span>
                  <span className="text-sm font-medium">{CLASS_LABELS[c]}</span>
                </span>
                <span className="font-mono text-xs text-muted-2">
                  AP {(PER_CLASS_AP[c] * 100).toFixed(1)}
                </span>
              </button>
            ))}
          </div>

          <Card className="relative overflow-hidden scanline">
            <div className="mb-6 flex items-center justify-between">
              <div>
                <div className="font-mono text-xs uppercase tracking-wider text-accent">
                  {String(CLASS_NAMES.indexOf(active) + 1).padStart(2, "0")} / 06
                </div>
                <h3 className="mt-1 text-xl font-semibold text-foreground">{CLASS_LABELS[active]}</h3>
              </div>
              <div className="rounded-md border border-border bg-surface px-3 py-1.5 text-right">
                <div className="font-mono text-[10px] uppercase tracking-wider text-muted-2">AP@50:95</div>
                <div className="font-tabular text-lg font-semibold text-accent">
                  {(PER_CLASS_AP[active] * 100).toFixed(1)}%
                </div>
              </div>
            </div>
            <p className="max-w-2xl text-sm leading-relaxed text-muted">{CLASS_DESCRIPTIONS[active]}</p>

            <div className="mt-8 grid grid-cols-3 gap-3 border-t border-border pt-6">
              {["open", "short", "mousebite"].includes(active) ? null : null}
              <div>
                <div className="font-mono text-[10px] uppercase tracking-wider text-muted-2">Class ID</div>
                <div className="mt-1 font-mono text-sm text-foreground">{CLASS_NAMES.indexOf(active)}</div>
              </div>
              <div>
                <div className="font-mono text-[10px] uppercase tracking-wider text-muted-2">Match Rule</div>
                <div className="mt-1 font-mono text-sm text-foreground">IoU ≥ 0.50</div>
              </div>
              <div>
                <div className="font-mono text-[10px] uppercase tracking-wider text-muted-2">Dataset</div>
                <div className="mt-1 font-mono text-sm text-foreground">DeepPCB</div>
              </div>
            </div>
          </Card>
        </div>
      </div>
    </section>
  );
}
